-- Q1. WAQTD SNAME , DOB , TNAME ,BRANCH FOR ALL THE STUDENTS 
--EVEN THE STD ARE NOT ASSIGNED TO ANY TRAINERS  ?
SELECT SNAME ,DOB,TNAME ,BRANCH
from STD LEFT JOIN TRN
ON STD.TID=TRN.TID;

-- Q2.WAQTD ALL THE STUDENTS DETAILS AND THEIR TRAINERS DETAILS 
--    FOR ALL TRAINER EVEN THE TRAINER THEY ARE NOT ASSIGNED TO ANY  STUDENTS ?

SELECT STD.*,TRN.*
FROM STD RIGHT JOIN TRN
ON STD.TID=TRN.TID
;
-- Q3.WAQTD ALL THE TRAINERS AND STUDENTS DETAILS EVEN THE STUDENTS WHO 
--ARE NOT ASSIGNED TO ANY TRAINERS AND ALSO THE TRAINERS WHO ARE NOT ASSIGNED TO ANY STUDENTS ?


SELECT STD.*,TRN.*
FROM STD FULL JOIN TRN
ON STD.TID=TRN.TID
;