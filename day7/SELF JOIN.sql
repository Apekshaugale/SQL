-- 162) WAQTD EMPLOYEES DNAME AND MANAGER LOC INCLUDING EMPLOYEES SALARY AND MANAGER DEPTNO 
-- FOR ALL THE EMPLOYEES WHO ARE HIRED BEFORE THE MANAGERS MANAGE ?
SELECT DE.DNAME, DM.LOC, E.SAL, M.DEPTNO
FROM EMP1 E, EMP1 M, EMP1 MM, DEPT DE, DEPT DM
WHERE E.MGR = M.EMPNO
AND M.MGR = MM.EMPNO
AND E.DEPTNO = DE.DEPTNO
AND M.DEPTNO = DM.DEPTNO
AND E.HIREDATE < MM.HIREDATE;

-- 163) WAQTD MANAGERS MANAGER NAME FOR ALL THE EMPLOYEES WHO ARE WORKING IN MANAGERS 
-- LOCATION AND NOT WORKING IN MANAGES MANAGERS LOCATION ?
SELECT MM.ENAME 
FROM EMP1 E ,EMP1 M, EMP1 MM ,DEPT DE,DEPT DM ,DEPT DMM
WHERE E.MGR=M.EMPNO
AND E.DEPTNO=DE.DEPTNO
AND M.MGR=MM.EMPNO 
AND M.DEPTNO=DM.DEPTNO
AND MM.DEPTNO=DMM.DEPTNO 
AND  DE.LOC = DM.LOC
AND DE.LOC <> DMM.LOC;
-- 164) WAQTD MANAGER NAME FOR THE MANAGERS MANAGER WHO ARE WORKING IN DEPTNO 20 AS ACTUAL 
-- MANAGER AND EARNING SALARY MORE THEN THE EMPLOYEES ?
SELECT M.ENAME 
FROM EMP1 E ,EMP1 M, EMP1 MM ,DEPT DE,DEPT DM ,DEPT DMM
WHERE E.MGR=M.EMPNO
AND E.DEPTNO=DE.DEPTNO
AND M.MGR=MM.EMPNO 
AND M.DEPTNO=DM.DEPTNO
AND MM.DEPTNO=DMM.DEPTNO 
AND DMM.DEPTNO=20 AND MM.SAL >E.SAL;
-- 165) WAQTD MANAGERS DNAME AND MANAGERS MANAGER LOC FOR THE EMPLOYEES WHO ARE WORKING IN BOSTON ?

SELECT DM.DNAME,DMM.LOC
FROM EMP1 E ,EMP1 M, EMP1 MM ,DEPT DE,DEPT DM ,DEPT DMM
WHERE E.MGR=M.EMPNO
AND E.DEPTNO=DE.DEPTNO
AND M.MGR=MM.EMPNO 
AND M.DEPTNO=DM.DEPTNO
AND MM.DEPTNO=DMM.DEPTNO 
AND DE.LOC='BOSTON';
-- 166) WAQTD EMPLOYEES DNAME FOR THE MANAGERS MANAGER WHOSE SAL ARE MORE THAN MANAGER AND LESS THAN EMPLOYEES ?
SELECT DE.DNAME
FROM EMP1 E, EMP1 M, EMP1 MM, DEPT DE
WHERE E.MGR = M.EMPNO
AND M.MGR = MM.EMPNO
AND E.DEPTNO = DE.DEPTNO
AND MM.SAL > M.SAL
AND MM.SAL < E.SAL;
-- 167) WAQTD EMPLOYEES LOC AND MANAGERS MANAGERS LOC FOR THE MANAGER WHO ARE HIRED BEFORE
--  THE EMPLOYEE AND EARNING SALARY MORE THAN THE EMPLOYEES ?

SELECT DE.LOC ,DMM.LOC 
FROM EMP1 E,EMP1 M,EMP1 MM,DEPT DE,DEPT DM,DEPT DMM
WHERE E.MGR=M.EMPNO AND M.MGR=MM.EMPNO
AND M.DEPTNO=DM.DEPTNO
AND MM.DEPTNO=DMM.DEPTNO 
AND E.DEPTNO=DE.DEPTNO
AND M.HIREDATE <E.HIREDATE AND M.SAL>E.SAL;