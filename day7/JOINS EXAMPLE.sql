-- WAQTD ENAME ,LOC , AND SAL OF ALL THE EMPLOYEES EVEN IF THEY NOT 
-- ASSIGNED TO ANY DEPARTMENT . WORKING AS SALESMAN AND EARNING SALARY
--  MORE THEN 1000 ?
SELECT E.ENAME, D.LOC, E.SAL
FROM EMP1 E
LEFT OUTER JOIN DEPT D
ON E.DEPTNO = D.DEPTNO
WHERE E.JOB = 'SALESMAN'
AND E.SAL > 1000;

-- WAQTD ENAME ,LOC ,DNAME  AND SAL OF ALL THE DEPARTMENTS EVEN IN THAT THERE
--  IS NO EMPLOYEES ARE WORKING AND LOC BELONGS TO NEW YORK ?(RIGHT)

SELECT ENAME,LOC,DNAME,SAL
FROM EMP1 RIGHT JOIN DEPT
ON EMP1.DEPTNO=DEPT.DEPTNO
WHERE LOC='NEW YORK';  
-- WAQTD ENAME ,LOC , AND DNAME ,HIREDATE  SAL OF ALL THE EMPLOYEES EVEN IF
--  THEY NOT ASSIGNED TO ANY DEPARTMENT . WORKING AS SALESMAN AND WHOSE NAME 
--  STARTS WITH CONSONANTS  ?

SELECT ENAME,LOC,DNAME,HIREDATE,SAL
FROM EMP1 LEFT JOIN DEPT 
ON EMP1.DEPTNO=DEPT.DEPTNO
WHERE JOB='SALESMAN' AND ENAME NOT LIKE  'A%'
AND ENAME NOT LIKE  'E%' AND ENAME NOT LIKE 
'I%'AND ENAME NOT LIKE 'O%' AND ENAME NOT LIKE  'U%';   
-- WAQTD ALL THE EMPLOYEES DETAILS AND THEIR DEPARTMENT DETAILS EVEN THE 
-- EMPLOYEES ARE NOT ASSIGNED TO ANY LOCATION 
-- IF DEPARTMENT NAME HAVING A CHARACTERS 

SELECT EMP1.*,DEPT.*
FROM EMP1 LEFT JOIN DEPT
ON EMP1.DEPTNO=DEPT.DEPTNO
WHERE  DNAME  LIKE  '%A%';